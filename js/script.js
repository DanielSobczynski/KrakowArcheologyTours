function setLanguage(lang) {
    const selected = translations[lang] ? lang : "en";
    document.documentElement.lang = selected;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (Object.prototype.hasOwnProperty.call(translations[selected], key)) {
            element.innerHTML = translations[selected][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (Object.prototype.hasOwnProperty.call(translations[selected], key)) {
            element.setAttribute("placeholder", translations[selected][key]);
        }
    });

    document.querySelectorAll(".lang-btn").forEach((button) => {
        button.classList.toggle("active", button.dataset.lang === selected);
    });

    try {
        localStorage.setItem("preferredLanguage", selected);
    } catch (error) {
        // The page still works if browser storage is unavailable.
    }

    // Keep expanded/collapsed labels correct after switching languages.
    document.querySelectorAll(".read-more").forEach((button) => {
        const expanded = button.getAttribute("aria-expanded") === "true";
        const label = translations[selected][expanded ? "readLess" : "readMore"];
        button.innerHTML = `${label} <span aria-hidden="true">${expanded ? "−" : "＋"}</span>`;
    });
}

document.addEventListener("DOMContentLoaded", () => {
    let savedLanguage = "en";
    try {
        savedLanguage = localStorage.getItem("preferredLanguage") || "en";
    } catch (error) {
        // Use English as the default language.
    }

    document.querySelectorAll(".lang-btn").forEach((button) => {
        button.addEventListener("click", () => setLanguage(button.dataset.lang));
    });

    document.querySelectorAll(".read-more").forEach((button) => {
        button.addEventListener("click", () => {
            const panel = document.getElementById(button.getAttribute("aria-controls"));
            if (!panel) return;

            const expanded = button.getAttribute("aria-expanded") === "true";
            button.setAttribute("aria-expanded", String(!expanded));
            panel.hidden = expanded;

            const lang = document.documentElement.lang || "en";
            const label = translations[lang][expanded ? "readMore" : "readLess"];
            button.innerHTML = `${label} <span aria-hidden="true">${expanded ? "＋" : "−"}</span>`;
        });
    });

    setLanguage(savedLanguage);

    const year = document.getElementById("year");
    if (year) year.textContent = new Date().getFullYear();

    // Formspree AJAX submission: keeps visitors on the website after sending.
    const contactForm = document.getElementById("contact-form");
    const formStatus = document.getElementById("contact-form-status");

    if (contactForm && formStatus) {
        contactForm.addEventListener("submit", async (event) => {
            event.preventDefault();

            const submitButton = contactForm.querySelector("[type=\"submit\"]");
            const lang = document.documentElement.lang === "pl" ? "pl" : "en";
            const messages = translations[lang];

            formStatus.hidden = true;
            formStatus.textContent = "";
            formStatus.className = "form-status";
            submitButton.disabled = true;
            submitButton.textContent = messages.formSending;

            try {
                const response = await fetch(contactForm.action, {
                    method: "POST",
                    body: new FormData(contactForm),
                    headers: { "Accept": "application/json" }
                });

                const result = await response.json().catch(() => null);

                if (response.ok) {
                    formStatus.textContent = messages.formSuccess;
                    formStatus.classList.add("is-success");
                    contactForm.reset();
                } else {
                    formStatus.textContent = messages.formError;
                    formStatus.classList.add("is-error");
                }
            } catch (error) {
                formStatus.textContent = messages.formNetworkError;
                formStatus.classList.add("is-error");
            } finally {
                formStatus.hidden = false;
                submitButton.disabled = false;
                submitButton.textContent = messages.formSubmit;
            }
        });
    }
});
